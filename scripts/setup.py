"""Install repository runtimes and register supplied artifacts. Never trains models."""
from __future__ import annotations

import argparse
import ctypes.util
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import urllib.request
import venv

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from environment import read_environment

CONFIG = ROOT / "backend/config"
METHODS = json.loads((CONFIG / "methods.json").read_text())
METHODS.update(json.loads((CONFIG / "repository_methods.json").read_text()))
PROFILES = json.loads((CONFIG / "runtime_profiles.json").read_text())
REQUIREMENTS = ROOT / "backend/integrations/repository_methods/requirements"
ENV_FILE = ROOT / ".env.gpu"
LAWA_FILES = {
    "WATERMARK_LAWA_WEIGHT": "weights/LaWa/last.ckpt",
    "WATERMARK_LAWA_FIRST_STAGE": "weights/first_stage_models/first_stage_KL-f8.ckpt",
    "WATERMARK_LAWA_SD_CHECKPOINT": "weights/stable-diffusion-v1/model.ckpt",
}
ARTIFACTS = {key: method for method, spec in METHODS.items() for key in spec["setup_artifacts"]}


class SetupError(Exception):
    pass


def run(command, **kwargs):
    return subprocess.run([str(part) for part in command], check=True, **kwargs)


def selected_methods(value):
    methods = list(METHODS) if value == "all" else list(dict.fromkeys(value.split(",")))
    unknown = set(methods) - METHODS.keys()
    if unknown:
        raise SetupError("Unknown methods: " + ", ".join(sorted(unknown)))
    return methods


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def configured_values():
    values = read_environment(ENV_FILE)
    keys = set(values) | {"LDWM_BACKEND_PYTHON", "LDWM_NODE_BIN"}
    for spec in METHODS.values():
        keys.update((spec["python_env"], spec["repo_env"], *spec["setup_artifacts"]))
        if spec.get("model_env"):
            keys.update((spec["model_env"], spec["model_env"].removesuffix("_MODEL_ID") + "_MODEL_REVISION"))
    for key in keys:
        if key in os.environ:
            values[key] = os.environ[key]
    return values


def defaults(values, methods):
    result = dict(values)
    result.setdefault("LDWM_BACKEND_PYTHON", str(ROOT / ".venvs/backend/bin/python"))
    result.setdefault("PYTHONDONTWRITEBYTECODE", "1")
    for method in methods:
        spec = METHODS[method]
        profile = "wind" if spec["profile"] == "seal" else spec["profile"]
        result.setdefault(spec["repo_env"], str((ROOT / "backend" / spec["repo_path"]).resolve()))
        result.setdefault(spec["python_env"], str(ROOT / f".venvs/{profile}/bin/python"))
        if spec.get("model_env") and method != "serum":
            result.setdefault(spec["model_env"], spec["default_model"])
            prefix = spec["model_env"].removesuffix("_MODEL_ID")
            result.setdefault(prefix + "_MODEL_REVISION", "main")
    if "lawa" in methods:
        for key, relative in LAWA_FILES.items():
            candidate = Path(result["WATERMARK_LAWA_REPO"]) / relative
            if candidate.is_file():
                result.setdefault(key, str(candidate))
    return result


def write_environment(values):
    # Fully expanded assignments also work with systemd EnvironmentFile.
    text = "# Generated by setup.sh. Local paths; keep this file private.\n"
    text += "\n".join(f"{key}={json.dumps(value, ensure_ascii=False)}" for key, value in sorted(values.items())) + "\n"
    if ENV_FILE.exists():
        if ENV_FILE.read_text() == text:
            return
        backup = ENV_FILE.with_name(".env.gpu.bak." + datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%f"))
        shutil.copyfile(ENV_FILE, backup)
        backup.chmod(0o600)
        print(f"Previous configuration saved to {backup.name}")
    temporary = ENV_FILE.with_name(".env.gpu.tmp")
    descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(descriptor, "w") as stream:
        stream.write(text)
    temporary.chmod(0o600)
    temporary.replace(ENV_FILE)


def import_artifacts(folder, methods):
    folder = folder.expanduser().resolve()
    manifest = json.loads((folder / "manifest.json").read_text())
    if manifest.get("schema_version") != 1:
        raise SetupError("Unsupported artifact manifest version")
    for method, revision in manifest.get("revisions", {}).items():
        if method in methods and revision != METHODS[method]["revision"]:
            raise SetupError(f"Artifact bundle uses a different {method} source revision")
    values = {}
    for key, entry in manifest["files"].items():
        if key not in ARTIFACTS:
            raise SetupError(f"Unknown artifact variable in bundle: {key}")
        if ARTIFACTS[key] not in methods:
            continue
        path = (folder / entry["path"]).resolve()
        if folder not in path.parents or not path.is_file():
            raise SetupError(f"Missing or invalid bundled file for {key}")
        if sha256(path) != entry["sha256"]:
            raise SetupError(f"Checksum mismatch for {key}")
        values[key] = str(path)
    print(f"Verified {len(values)} supplied artifact files")
    return values


def export_artifacts(folder, values, methods):
    folder = folder.expanduser().resolve()
    if folder.exists() and any(folder.iterdir()):
        raise SetupError("Export destination must be new or empty; existing files were preserved")
    sources = {}
    missing = []
    for key, method in ARTIFACTS.items():
        if method not in methods:
            continue
        path = Path(values.get(key, ""))
        if not values.get(key) or not path.is_file():
            missing.append(key)
            continue
        sources[key] = path
    if missing:
        raise SetupError("Configure these files before exporting (or select fewer --methods): " + ", ".join(missing))
    manifest = {"schema_version": 1, "revisions": {method: METHODS[method]["revision"] for method in methods}, "files": {}}
    for key, source in sources.items():
        destination = folder / ARTIFACTS[key] / (key.lower() + source.suffix)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, destination)
        destination.chmod(0o640)
        manifest["files"][key] = {"path": destination.relative_to(folder).as_posix(), "sha256": sha256(destination), "size": destination.stat().st_size}
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Exported {len(sources)} artifacts to {folder}. No tokens, job keys, datasets or virtual environments were included.")


def ensure_uv():
    existing = shutil.which("uv")
    if existing:
        return existing
    bootstrap = ROOT / ".tools/bootstrap"
    python = bootstrap / "bin/python"
    if not python.exists():
        venv.EnvBuilder(with_pip=True).create(bootstrap)
    uv = bootstrap / "bin/uv"
    if not uv.exists():
        run([python, "-m", "pip", "install", "uv>=0.8,<1"])
    return str(uv)


def ensure_node():
    candidates = [shutil.which("node"), str(ROOT / ".tools/node/bin/node")]
    for executable in candidates:
        if not executable or not Path(executable).is_file():
            continue
        version = subprocess.check_output([executable, "-p", "process.versions.node"], text=True).strip()
        major, minor, *_ = map(int, version.split("."))
        if major > 22 or (major == 22 and minor >= 12):
            return str(Path(executable).parent)
    if platform.system() != "Linux" or platform.machine() != "x86_64":
        raise SetupError("Install Node.js 22.12 or newer before using --ui-only on this machine")
    base = "https://nodejs.org/dist/latest-v22.x/"
    with urllib.request.urlopen(base + "SHASUMS256.txt", timeout=60) as response:
        checksums = response.read().decode()
    checksum, filename = next(line.split() for line in checksums.splitlines() if line.endswith("-linux-x64.tar.xz"))
    archive = ROOT / ".tools" / filename
    archive.parent.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(base + filename, timeout=60) as response, archive.open("wb") as stream:
        shutil.copyfileobj(response, stream)
    if sha256(archive) != checksum:
        raise SetupError("Node.js download checksum did not match")
    destination = ROOT / ".tools/node"
    destination.mkdir(parents=True, exist_ok=True)
    run(["tar", "-xJf", archive, "--strip-components=1", "-C", destination])
    archive.unlink()
    return str(destination / "bin")


def install_profile(uv, name):
    spec = PROFILES[name]
    path = ROOT / f".venvs/{name}"
    python = path / "bin/python"
    if not python.exists():
        run([uv, "venv", "--python", spec["python"], path])
    cuda = spec["cuda"]
    suffix = "+" + cuda if spec["torch"].startswith("1.") else ""
    run([uv, "pip", "install", "--python", python,
         "torch==" + spec["torch"] + suffix, "torchvision==" + spec["torchvision"] + suffix,
         "--index-url", "https://download.pytorch.org/whl/" + cuda])
    # pyldpc's setup imports NumPy without declaring a build dependency.
    if name == "gaussian-shannon":
        run([uv, "pip", "install", "--python", python, "numpy==1.26.4", "setuptools<81", "wheel"])
        run([uv, "pip", "install", "--python", python, "--no-build-isolation", "pyldpc==0.7.9"])
    command = [uv, "pip", "install", "--python", python, "-r", REQUIREMENTS / spec.get("requirements", name + ".txt")]
    if name == "gaussian-shannon":
        command += ["--no-build-isolation-package", "pyldpc"]
    run(command)
    run([uv, "pip", "check", "--python", python])
    lock = ROOT / f"work/setup/{name}.freeze.txt"
    lock.parent.mkdir(parents=True, exist_ok=True)
    with lock.open("w") as stream:
        run([uv, "pip", "freeze", "--python", python], stdout=stream)


def prepare_serum_config(values):
    key = "WATERMARK_SERUM_CONFIG"
    if not values.get(key) or not Path(values[key]).is_file():
        return
    target = ROOT / "work/config/serum.yaml"
    target.parent.mkdir(parents=True, exist_ok=True)
    # Use SERUM's own YAML dependency; the gateway itself needs only stdlib.
    code = """
import os, pathlib, sys, yaml
source, destination = map(pathlib.Path, sys.argv[1:])
config = yaml.safe_load(source.read_text())
model = config['diffusion']['stable_diffusion_model_id']
model = os.environ.get('WATERMARK_SERUM_MODEL_ID') or model
if model == 'stabilityai/stable-diffusion-2-1-base':
    model = 'sd2-community/stable-diffusion-2-1-base'
if (model.startswith('/') or model.startswith('.')) and not pathlib.Path(model).is_dir():
    raise SystemExit('SERUM config references a model folder from another machine. Set WATERMARK_SERUM_MODEL_ID to the matching model before setup.')
config['diffusion']['stable_diffusion_model_id'] = model
config['experiment_dir'] = str(destination.parent / 'serum-inference')
destination.write_text(yaml.safe_dump(config, sort_keys=False))
"""
    run([values["WATERMARK_SERUM_PYTHON"], "-c", code, values[key], target], env={**os.environ, **values})
    values[key] = str(target)


def download_models(values, methods):
    downloaded = set()
    for method in methods:
        if method == "lawa":
            print("LaWa uses its supplied checkpoint files; CLIP text assets download on first use.")
            continue
        spec = METHODS[method]
        if method == "serum":
            code = "import yaml,sys; print(yaml.safe_load(open(sys.argv[1]))['diffusion']['stable_diffusion_model_id'])"
            model = subprocess.check_output([values[spec["python_env"]], "-c", code, values["WATERMARK_SERUM_CONFIG"]], text=True).strip()
        else:
            model = values[spec["model_env"]]
        revision = values.get(spec["model_env"].removesuffix("_MODEL_ID") + "_MODEL_REVISION", "main")
        models = [(model, revision)]
        if method == "seal":
            models += [("Salesforce/blip2-flan-t5-xl", "main"), ("kasraarabi/finetuned-caption-embedding", "main")]
        for model, revision in models:
            if Path(model).is_dir() or (model, revision) in downloaded:
                continue
            print(f"Caching {model} ({revision})", flush=True)
            code = "from huggingface_hub import snapshot_download; import sys; snapshot_download(repo_id=sys.argv[1], revision=sys.argv[2], ignore_patterns=['onnx/*','openvino/*','*.ckpt','*.msgpack','*.h5','*.fp16.*'])"
            run([values[spec["python_env"]], "-c", code, model, revision], env={**os.environ, **values})
            downloaded.add((model, revision))


def check(values, methods):
    failed = False
    for method in methods:
        print(f"\nChecking {method}", flush=True)
        outcome = subprocess.run([sys.executable, ROOT / "backend/integrations/repository_methods/setup_repositories.py", "--method", method, "--check"], env={**os.environ, **values})
        failed |= outcome.returncode != 0
    return not failed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--methods", default="all", help="Comma-separated method IDs, or all")
    parser.add_argument("--artifacts", type=Path, help="Directory containing a supplied manifest.json and checkpoints")
    parser.add_argument("--export-artifacts", type=Path, metavar="DIRECTORY", help="Export configured trained files from an existing installation")
    parser.add_argument("--download-models", action="store_true", help="Cache model weights now instead of on first use")
    parser.add_argument("--check", action="store_true", help="Check existing configuration; install nothing")
    parser.add_argument("--plan", action="store_true", help="Show selected runtimes and artifacts; change nothing")
    parser.add_argument("--ui-only", action="store_true", help="Install the frontend and gateway, without GPU runtimes")
    args = parser.parse_args()
    methods = selected_methods(args.methods)
    profiles = list(dict.fromkeys("wind" if METHODS[m]["profile"] == "seal" else METHODS[m]["profile"] for m in methods))
    values = defaults(configured_values(), methods)
    if args.plan:
        print("Methods: " + ", ".join(methods))
        print("Runtime groups: " + (", ".join(profiles) if not args.ui_only else "frontend and gateway only"))
        print("Required trained files: " + ", ".join(key for key, method in ARTIFACTS.items() if method in methods))
        print("No training is performed. CUDA/model inference must be tested separately.")
        return 0
    if args.export_artifacts:
        export_artifacts(args.export_artifacts, values, methods)
        return 0
    if args.check:
        return 0 if check(values, methods) else 2
    if not args.ui_only:
        if platform.system() != "Linux" or platform.machine() != "x86_64":
            raise SetupError("Full inference requires Linux x86_64 with NVIDIA CUDA. Use WSL2 on Windows, or --ui-only on macOS.")
        if os.geteuid() == 0:
            raise SetupError("Run setup as the same non-root user that will run the application, for example ubuntu. Use sudo only to install OS packages.")
        if not shutil.which("nvidia-smi"):
            raise SetupError("Install the NVIDIA driver (or enable CUDA in WSL2); nvidia-smi was not found")
        run(["nvidia-smi", "--query-gpu=name,driver_version,memory.total", "--format=csv,noheader"])
        libraries = (["zbar"] if "sfwmark" in methods else []) + (["magic"] if "lawa" in methods else [])
        missing = [library for library in libraries if not ctypes.util.find_library(library)]
        if missing:
            raise SetupError("Missing OS libraries: " + ", ".join(missing) + ". See README.md for the apt install command.")
    if not shutil.which("git"):
        raise SetupError("Install Git before setup")
    if args.artifacts:
        values.update(import_artifacts(args.artifacts, methods))
    os.environ.setdefault("UV_PYTHON_INSTALL_DIR", str(ROOT / ".tools/python"))
    uv = ensure_uv()
    backend = ROOT / ".venvs/backend/bin/python"
    if values["LDWM_BACKEND_PYTHON"] == str(backend) and not backend.exists():
        run([uv, "venv", "--python", "3.12", backend.parent.parent])
    if not os.access(values["LDWM_BACKEND_PYTHON"], os.X_OK):
        raise SetupError("LDWM_BACKEND_PYTHON does not point to an executable Python; fix the existing override in .env.gpu")
    values["LDWM_NODE_BIN"] = ensure_node()
    frontend_env = {**os.environ, **{key: value for key, value in values.items() if key.startswith("VITE_")},
                    "CI": "1", "PATH": values["LDWM_NODE_BIN"] + os.pathsep + os.environ.get("PATH", "")}
    # The tracked pnpm lockfile is the frontend's dependency lock.
    run(["npx", "--yes", "pnpm@10.11.0", "install", "--frozen-lockfile"], cwd=ROOT / "watermark-lab", env=frontend_env)
    run(["npx", "--yes", "pnpm@10.11.0", "run", "build"], cwd=ROOT / "watermark-lab", env=frontend_env)
    if not args.ui_only:
        for method in methods:
            run([sys.executable, ROOT / "backend/integrations/repository_methods/setup_repositories.py", "--method", method, "--clone"], env={**os.environ, **values})
        for name in profiles:
            managed = str(ROOT / f".venvs/{name}/bin/python")
            if any(values[METHODS[m]["python_env"]] == managed for m in methods):
                print(f"\nInstalling {name}", flush=True)
                install_profile(uv, name)
        if "serum" in methods:
            prepare_serum_config(values)
    write_environment(values)
    state = ROOT / "work/setup/installation.json"
    state.parent.mkdir(parents=True, exist_ok=True)
    state.write_text(json.dumps({"methods": methods, "ui_only": args.ui_only}, indent=2))
    if not args.ui_only and not check(values, methods):
        print("\nInstallation files are prepared, but setup checks failed. Supply the missing artifacts or fix the reported runtime, then rerun setup. Training was not started.")
        return 2
    if args.download_models and not args.ui_only:
        download_models(values, methods)
    print("\nSetup checks passed. Start with: bash start.sh")
    print("Run generation and analysis for each method to validate GPU inference. Import checks do not measure watermark quality.")
    return 0


if __name__ == "__main__":
    if sys.version_info < (3, 10):
        raise SystemExit("Setup requires Python 3.10 or newer")
    try:
        raise SystemExit(main())
    except (SetupError, OSError, ValueError, KeyError, subprocess.CalledProcessError) as exc:
        print(f"Setup stopped: {exc}", file=sys.stderr)
        raise SystemExit(1)
